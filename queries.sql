-- Задание 7. JOIN — заказы с названиями товаров
SELECT Заказ.дата, Заказ.клиент, Товар.название, Заказ.количество
FROM Заказ
JOIN Товар ON Заказ.товар_id = Товар.id;

-- Задание 8. Общая сумма всех заказов
SELECT SUM(Товар.цена * Заказ.количество) AS сумма
FROM Заказ
JOIN Товар ON Заказ.товар_id = Товар.id;

-- Задание 9. Количество заказов по клиентам
SELECT клиент, COUNT(*) AS заказов
FROM Заказ
GROUP BY клиент;

-- Задание 10. Мой запрос
-- Что хочу получить: на какую сумму заказал каждый клиент (по убыванию суммы)
SELECT Заказ.клиент, SUM(Товар.цена * Заказ.количество) AS сумма
FROM Заказ
JOIN Товар ON Заказ.товар_id = Товар.id
GROUP BY Заказ.клиент
ORDER BY сумма DESC;
